# ---------------------------------------------------------------------------
# MarkItDown instance factory
# ---------------------------------------------------------------------------
def _get_markitdown_instance() -> MarkItDown:
    """Create a MarkItDown instance, optionally with LLM client."""
    openai_key = os.environ.get("OPENAI_API_KEY")
    openai_base = os.environ.get("OPENAI_BASE_URL")
    llm_model = "openai.gpt-oss-120b"
    client = None

    if openai_key and openai_key.strip() and openai_key != "YOUR_OPENAI_API_KEY":
        try:
            from openai import OpenAI

            test_client = OpenAI(
                api_key=openai_key,
                base_url=openai_base if openai_base else None,
                timeout=3.0,
            )
            test_client.chat.completions.create(
                model=llm_model,
                messages=[{"role": "user", "content": "ping"}],
                max_tokens=1,
            )
            client = test_client
        except Exception:
            client = None

    if client:
        return MarkItDown(llm_client=client, llm_model=llm_model, enable_plugins=True)
    else:
        return MarkItDown(enable_plugins=True)


# ---------------------------------------------------------------------------
# PDF page-by-page extraction
# ---------------------------------------------------------------------------
def _extract_pdf_pages(
    pdf_path: str, markitdown: MarkItDown, page_limit: Optional[int] = None
) -> list[dict]:
    doc = fitz.open(pdf_path)
    total_pages = len(doc)
    pages_to_process = (
        range(min(page_limit, total_pages))
        if page_limit is not None
        else range(total_pages)
    )

    pages_data = []
    for page_idx in pages_to_process:
        page_num = page_idx + 1
        page = doc[page_idx]

        # Extract single page as temporary PDF
        page_doc = fitz.open()
        page_doc.insert_pdf(doc, from_page=page_idx, to_page=page_idx)

        fd, temp_pdf_path = tempfile.mkstemp(suffix=".pdf")
        os.close(fd)

        try:
            page_doc.save(temp_pdf_path)
            page_doc.close()

            res = markitdown.convert(temp_pdf_path)
            page_text = res.text_content

            # Strip generic "## Page 1" injected by markitdown for single-page exports
            page_text = re.sub(
                r"^#+\s*Page\s+1\s*\n?", "", page_text, flags=re.IGNORECASE
            ).strip()

            # Extract PyMuPDF text for comparison
            fitz_text = page.get_text("text").strip()

            # Decide which text source to use
            use_fitz = False
            if len(page_text) < 50 and len(fitz_text) >= 50:
                use_fitz = True
            elif len(page_text) > 0:
                mid_alnum_space = sum(
                    1 for c in page_text if c.isalnum() or c.isspace()
                )
                fitz_alnum_space = sum(
                    1 for c in fitz_text if c.isalnum() or c.isspace()
                )
                mid_ratio = (
                    mid_alnum_space / len(page_text) if len(page_text) > 0 else 0
                )
                fitz_ratio = (
                    fitz_alnum_space / len(fitz_text) if len(fitz_text) > 0 else 0
                )

                if mid_ratio < 0.6 and fitz_ratio > 0.8 and len(fitz_text) > 100:
                    use_fitz = True
                elif len(fitz_text) > len(page_text) * 1.5:
                    use_fitz = True

            if use_fitz:
                lines = fitz_text.splitlines()
                cleaned_lines = []
                i = 0
                while i < len(lines):
                    line = lines[i].strip()
                    if line in ["•", "–", "▪", "*", "-"] or (
                        len(line) == 1 and not line.isalnum()
                    ):
                        if i + 1 < len(lines):
                            next_line = lines[i + 1].strip()
                            cleaned_lines.append(f"{line} {next_line}")
                            i += 2
                            continue
                    cleaned_lines.append(lines[i])
                    i += 1
                page_text = "\n".join(cleaned_lines)

            # Inject topic heading if none exists
            existing_heading = re.match(r"^#+\s+.+", page_text.lstrip())
            if not existing_heading:
                topic = _extract_content_topic(page_text)
                if topic:
                    page_text = f"## {topic}\n\n{page_text}"

            # Extract images from this page
            image_list = page.get_images(full=True)
            seen_xrefs = set()
            img_index = 1
            for img in image_list:
                try:
                    xref = img[0]
                    if xref in seen_xrefs:
                        continue
                    seen_xrefs.add(xref)

                    width = img[2]
                    height = img[3]
                    if width < 50 or height < 50:
                        continue

                    base_image = doc.extract_image(xref)
                    image_bytes = base_image["image"]
                    image_ext = base_image["ext"]

                    base64_data = base64.b64encode(image_bytes).decode("utf-8")
                    mime_type = f"image/{image_ext}"
                    if image_ext == "jpg":
                        mime_type = "image/jpeg"

                    page_text += f"\n\n![Image page {page_num}, image {img_index}](data:{mime_type};base64,{base64_data})"
                    img_index += 1
                except Exception:
                    pass

            blocks_data = _parse_markdown_to_blocks(page_text)
            if not blocks_data:
                blocks_data = [{"type": "text", "content": page_text}]

            pages_data.append(
                {"page_number": page_num, "text": page_text, "blocks": blocks_data}
            )
        finally:
            if os.path.exists(temp_pdf_path):
                os.unlink(temp_pdf_path)

    doc.close()
    return pages_data


# ---------------------------------------------------------------------------
# Markdown parsing helpers
# ---------------------------------------------------------------------------
def _parse_markdown_to_blocks(md_text: str) -> list[dict]:
    blocks = []
    lines = md_text.splitlines()

    current_block_type = None
    current_block_content = []
    current_level = None

    def flush():
        nonlocal current_block_type, current_block_content, current_level
        if not current_block_content:
            return
        content = "\n".join(current_block_content).strip()
        if content:
            block = {"type": current_block_type, "content": content}
            if current_level is not None:
                block["level"] = current_level
            blocks.append(block)
        current_block_content = []
        current_block_type = None
        current_level = None

    i = 0
    while i < len(lines):
        line = lines[i]
        trimmed = line.strip()

        if trimmed.startswith("#"):
            parts = trimmed.split(" ", 1)
            header_symbols = parts[0]
            if all(char == "#" for char in header_symbols) and len(parts) > 1:
                flush()
                current_block_type = "heading"
                current_level = len(header_symbols)
                current_block_content = [parts[1].strip()]
                flush()
                i += 1
                continue

        if trimmed.startswith("|"):
            if current_block_type != "table":
                flush()
                current_block_type = "table"
            current_block_content.append(line)
            i += 1
            continue

        if not trimmed:
            flush()
        else:
            if current_block_type not in ["text", None]:
                flush()
            current_block_type = "text"
            current_block_content.append(line)
        i += 1

    flush()
    return blocks


def _extract_content_topic(text: str) -> Optional[str]:
    """Extract the first meaningful heading or first non-trivial line as the page topic."""
    lines = text.splitlines()
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        if re.match(r"^#*\s*Page\s+\d+\s*$", stripped, re.IGNORECASE):
            continue
        if len(stripped) < 3:
            continue
        cleaned = re.sub(r"^[#•–▪\*\-\s]+", "", stripped).strip()
        if 5 <= len(cleaned) <= 120:
            return cleaned
    return None


