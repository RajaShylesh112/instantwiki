# Batch conversion: convert multiple files in one request
# ---------------------------------------------------------------------------
@app.post("/convert-batch")
async def convert_batch(req: ConvertBatchRequest):
    """Convert multiple documents in batch. Returns a list of results."""
    results = []
    
    for file_path in req.file_paths:
        if not os.path.isfile(file_path):
            results.append({
                "file_path": file_path,
                "success": False,
                "error": f"File not found: {file_path}",
                "pages": [],
                "images": []
            })
            continue
        
        try:
            markitdown_instance = _get_markitdown_instance()
            ext = os.path.splitext(file_path)[1].lower()

            if ext == ".pdf":
                pages_data = _extract_pdf_pages(file_path, markitdown_instance, req.page_limit)
            else:
                res = markitdown_instance.convert(file_path)
                md_text = res.text_content
                blocks_data = _parse_markdown_to_blocks(md_text)
                if not blocks_data:
                    blocks_data = [{"type": "text", "content": md_text}]
                pages_data = [{"page_number": 1, "text": md_text, "blocks": blocks_data}]

            results.append({
                "file_path": file_path,
                "success": True,
                "pages": pages_data,
                "images": []
            })

        except Exception as e:
            results.append({
                "file_path": file_path,
                "success": False,
                "error": str(e),
                "pages": [],
                "images": []
            })
    
    return {"results": results}


# ---------------------------------------------------------------------------
# Convert from base64-encoded bytes (no filesystem access needed)
# ---------------------------------------------------------------------------
@app.post("/convert-bytes", response_model=ConvertResponse)
async def convert_from_bytes(req: ConvertFromBytesRequest):
    """
    Convert a document from base64-encoded bytes.
    Useful when the file is in memory or coming from an upload stream.
    """
    try:
        file_bytes = base64.b64decode(req.file_bytes_base64)
        ext = os.path.splitext(req.filename)[1].lower()
        
        # Write to temp file, convert, then delete
        fd, temp_path = tempfile.mkstemp(suffix=ext)
        os.close(fd)
        
        try:
            with open(temp_path, "wb") as f:
                f.write(file_bytes)
            
            markitdown_instance = _get_markitdown_instance()
            
            if ext == ".pdf":
                pages_data = _extract_pdf_pages(temp_path, markitdown_instance, req.page_limit)
            else:
                res = markitdown_instance.convert(temp_path)
                md_text = res.text_content
                blocks_data = _parse_markdown_to_blocks(md_text)
                if not blocks_data:
                    blocks_data = [{"type": "text", "content": md_text}]
                pages_data = [{"page_number": 1, "text": md_text, "blocks": blocks_data}]
            
            return ConvertResponse(success=True, pages=pages_data, images=[])
        
        finally:
            if os.path.exists(temp_path):
                os.unlink(temp_path)
    
    except Exception as e:
        return ConvertResponse(success=False, error=str(e))


