# ---------------------------------------------------------------------------
# Conversion endpoint
# ---------------------------------------------------------------------------
@app.post("/convert", response_model=ConvertResponse)
async def convert_document(req: ConvertRequest):
    """Convert a single document file by path."""
    file_path = req.file_path
    page_limit = req.page_limit

    if not os.path.isfile(file_path):
        raise HTTPException(status_code=400, detail=f"File not found: {file_path}")

    try:
        markitdown_instance = _get_markitdown_instance()
        ext = os.path.splitext(file_path)[1].lower()

        if ext == ".pdf":
            pages_data = _extract_pdf_pages(file_path, markitdown_instance, page_limit)
        else:
            res = markitdown_instance.convert(file_path)
            md_text = res.text_content
            blocks_data = _parse_markdown_to_blocks(md_text)
            if not blocks_data:
                blocks_data = [{"type": "text", "content": md_text}]
            pages_data = [{"page_number": 1, "text": md_text, "blocks": blocks_data}]

        return ConvertResponse(success=True, pages=pages_data, images=[])

    except Exception as e:
        return ConvertResponse(success=False, error=str(e))


